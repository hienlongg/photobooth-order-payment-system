import datetime
import uuid
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin

if TYPE_CHECKING:
    from app.models.order import Order
    from app.models.tenant import Tenant


class Payment(Base, TimestampMixin):
    """
    Represents an outbound payment request created for an order.
    Holds checkout QR and link information generated by a PaymentProvider.
    """

    __tablename__ = "payments"
    __table_args__ = (
        Index("ix_payments_order_id", "order_id"),
        Index("ix_payments_tenant_id", "tenant_id"),
        Index("ix_payments_status", "status"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    tenant_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
    )
    order_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("orders.id", ondelete="CASCADE"),
        nullable=False,
    )
    provider: Mapped[str] = mapped_column(
        String(50), default="fake_payos", nullable=False
    )
    payment_reference: Mapped[str] = mapped_column(
        String(100), nullable=False, index=True
    )
    order_code: Mapped[str] = mapped_column(String(50), nullable=False)
    amount_vnd: Mapped[int] = mapped_column(Integer, nullable=False)
    status: Mapped[str] = mapped_column(
        String(30), default="PENDING", nullable=False
    )
    checkout_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    qr_code: Mapped[str | None] = mapped_column(Text, nullable=True)
    account_number: Mapped[str | None] = mapped_column(String(50), nullable=True)
    account_name: Mapped[str | None] = mapped_column(String(100), nullable=True)
    bin: Mapped[str | None] = mapped_column(String(20), nullable=True)
    expires_at: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    tenant: Mapped["Tenant"] = relationship("Tenant")
    order: Mapped["Order"] = relationship("Order", back_populates="payments")


class PaymentEvent(Base, TimestampMixin):
    """
    Immutable audit ledger of payment gateway webhook notifications.
    Enforces replay safety via unique constraint on (provider, reference).
    """

    __tablename__ = "payment_events"
    __table_args__ = (
        UniqueConstraint(
            "provider",
            "reference",
            name="uq_payment_events_provider_reference",
        ),
        Index("ix_payment_events_order_id", "order_id"),
        Index("ix_payment_events_status", "status"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    tenant_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="SET NULL"),
        nullable=True,
    )
    order_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("orders.id", ondelete="SET NULL"),
        nullable=True,
    )
    provider: Mapped[str] = mapped_column(
        String(50), default="fake_payos", nullable=False
    )
    reference: Mapped[str] = mapped_column(String(100), nullable=False)
    order_code: Mapped[str | None] = mapped_column(String(50), nullable=True)
    amount_vnd: Mapped[int] = mapped_column(Integer, nullable=False)
    status: Mapped[str] = mapped_column(
        String(30), nullable=False
    )  # PROCESSED, DUPLICATE, FLAGGED_FOR_REVIEW, LATE_PAYMENT, UNMATCHED, REJECTED
    is_valid_signature: Mapped[bool] = mapped_column(
        Boolean, default=True, nullable=False
    )
    raw_payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    order: Mapped["Order | None"] = relationship(
        "Order", back_populates="payment_events"
    )
